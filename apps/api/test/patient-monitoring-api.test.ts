import express from 'express';
import cookieParser from 'cookie-parser';
import request from 'supertest';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { randomBytes, randomUUID } from 'node:crypto';
import { initializeApp, deleteApp } from 'firebase-admin/app';
import { getFirestore } from 'firebase-admin/firestore';
import { getAuth } from 'firebase-admin/auth';
import { createAuthRouter } from '../src/modules/auth/auth.router.js';
import { createAuthMiddleware } from '../src/modules/auth/auth.middleware.js';
import { createCsrf } from '../src/modules/auth/csrf.js';
import { FirebaseIdentityProvider } from '../src/modules/auth/adapters/firebase-identity-provider.js';
import { UsersRepositoryAdapter } from '../src/modules/auth/adapters/users-repository-adapter.js';
import { UsersRepository } from '../src/modules/users/users.repository.js';
import { createPatientReadRouter } from '../src/modules/patients/patients.read.routes.js';
import { PatientMonitoringService } from '../src/modules/patients/patient-monitoring.service.js';
import { PatientsRepository } from '../src/modules/patients/patients.repository.js';
import { DevicesRepository } from '../src/modules/devices/devices.repository.js';
import { AssignmentsRepository } from '../src/modules/assignments/assignments.repository.js';
import { SessionsRepository } from '../src/modules/sessions/sessions.repository.js';
import { MeasurementsRepository } from '../src/modules/measurements/measurements.repository.js';
import { SessionsService } from '../src/modules/sessions/sessions.service.js';
import { createSessionsRouter } from '../src/modules/sessions/sessions.routes.js';
import { errorHandler } from '../src/middleware/error-handler.js';

const enabled = Boolean(process.env.FIRESTORE_EMULATOR_HOST && process.env.FIREBASE_AUTH_EMULATOR_HOST);
describe.skipIf(!enabled)('PL2 patient monitoring HTTP + real Auth/Firestore emulators', () => {
  const projectId = process.env.FIREBASE_PROJECT_ID;
  if (enabled && !projectId?.startsWith('demo-')) throw new Error('Solo demo-.');
  const firebase = enabled ? initializeApp({ projectId }, `http-${randomUUID()}`) : undefined;
  const db = firebase ? getFirestore(firebase) : undefined!;
  const uid = `viewer-${randomUUID()}`;
  const email = `${uid}@example.invalid`;
  const password = randomBytes(24).toString('base64url');
  const origin = 'http://localhost:5173';
  const patients = new PatientsRepository(() => db);
  const devices = new DevicesRepository(() => db);
  const assignments = new AssignmentsRepository(() => db);
  const sessions = new SessionsRepository(() => db);
  const measurements = new MeasurementsRepository(() => db);
  const config = { firebaseWebApiKey: 'emulator', appOrigins: [origin], csrfSecret: 'local-test-csrf-0123456789abcdefghijk',
    cookieSecure: false, sessionTtlMs: 3600000, loginRateLimit: { max: 100, windowMs: 900000 } };
  const identityProvider = new FirebaseIdentityProvider({ apiKey: 'emulator', emulatorHost: process.env.FIREBASE_AUTH_EMULATOR_HOST });
  const userRepository = new UsersRepositoryAdapter(new UsersRepository(() => db));
  const auth = createAuthMiddleware({ identityProvider, userRepository });
  const csrf = createCsrf({ secret: config.csrfSecret, secure: false, origins: [origin] });
  const app = express();
  app.use(express.json(), cookieParser());
  app.use('/api/v1/auth', createAuthRouter({ config, identityProvider, userRepository }));
  app.use('/api/v1/patients', auth.requireUser, createPatientReadRouter(new PatientMonitoringService(() => db), csrf.csrfProtection));
  app.use('/api/v1/sessions', auth.requireUser, csrf.csrfProtection, createSessionsRouter(new SessionsService({ sessions, measurements, devices })));
  app.use(errorHandler);
  const agent = request.agent(app);
  let patientId: string; let deviceId: string; let sessionId: string; let assignmentId: string; let token: string;
  beforeAll(async () => {
    await getAuth(firebase!).createUser({ uid, email, password });
    await db.collection('users').doc(uid).set({ uid, displayName: 'Consulta de integración', role: 'viewer', enabled: true, createdAt: new Date().toISOString() });
    const patient = await patients.create({ code: 'HTTP', displayName: 'Paciente de integración' }, 'integration-admin');
    const device = await devices.create({ code: 'SIM-HTTP', source: 'simulated' }, 'integration-admin');
    patientId = patient.id; deviceId = device.deviceId;
    const assignment = await assignments.create({ patientId, deviceId }, 'integration-admin'); assignmentId = assignment.id;
    const session = await sessions.createForAssignment(assignment.id, 'integration-admin'); sessionId = session.sessionId;
    await sessions.start(sessionId, 'integration-admin');
    await measurements.ingest(deviceId, { deviceId, sessionId, bootId: randomUUID(), sequence: 1, capturedAt: null, measurements: {
      heartRate: { value: null, status: 'no_contact', unit: 'bpm' }, spo2: { value: null, status: 'no_contact', unit: '%' },
      skinTemperature: { value: 33.5, status: 'valid', unit: 'C' },
    } });
    const firstCsrf = await agent.get('/api/v1/auth/csrf');
    const login = await agent.post('/api/v1/auth/login').set('Origin', origin).set('X-CSRF-Token', firstCsrf.body.data.csrfToken).send({ email, password });
    expect(login.status).toBe(200);
    expect(login.body.data.role).toBe('viewer');
    token = (await agent.get('/api/v1/auth/csrf')).body.data.csrfToken;
  }, 30000);
  afterAll(async () => { if (firebase) await deleteApp(firebase); });
  it('authenticates viewer, records one opening, and serves persisted history without poll auditing', async () => {
    expect((await request(app).get(`/api/v1/patients/${patientId}`)).status).toBe(401);
    expect((await agent.post(`/api/v1/patients/${patientId}/access`).send({ viewId: randomUUID() })).status).toBe(403);
    const viewId = randomUUID();
    const access = () => agent.post(`/api/v1/patients/${patientId}/access`).set('Origin', origin).set('X-CSRF-Token', token).send({ viewId });
    const first = await access();
    expect(first.status).toBe(201);
    expect(first.body.data.duplicate).toBe(false);
    const second = await access();
    expect(second.status).toBe(200);
    expect(second.body.data).toEqual({ eventId: first.body.data.eventId, duplicate: true });
    expect((await agent.get(`/api/v1/patients/${patientId}`)).body.data).not.toHaveProperty('activeAssignmentId');
    const latest = await agent.get(`/api/v1/patients/${patientId}/latest`);
    expect(latest.status).toBe(200);
    expect(latest.body.data).toMatchObject({ patientId, deviceId, assignmentId, sessionId });
    expect(latest.body.meta.connectionState).toBe('connected_with_recent_reading');
    expect(latest.body.data.measurements.heartRate.value).toBeNull();
    for (let index = 0; index < 2; index++) expect((await agent.get(`/api/v1/patients/${patientId}/measurements`)).body.data).toHaveLength(1);
    expect((await agent.get(`/api/v1/sessions?patientId=${patientId}&status=active`)).body.data[0].patientId).toBe(patientId);
    const events = await db.collection('auditLogs').where('targetId', '==', patientId).where('action', '==', 'patient.view').get();
    expect(events.size).toBe(1);
    expect((await agent.post('/api/v1/sessions').set('Origin', origin).set('X-CSRF-Token', token).send({ participantCode: 'P', deviceId })).status).toBe(403);
    expect((await agent.get('/api/v1/patients?enabled=false')).status).toBe(403);
  }, 30000);
  it('uses only the current board to report freshness and keeps the previous board in history', async () => {
    await sessions.finish(sessionId, 'integration-admin');
    await assignments.close(assignmentId, 'integration-admin');
    const next = await devices.create({ code: 'SIM-NEXT', source: 'simulated' }, 'integration-admin');
    await assignments.create({ patientId, deviceId: next.deviceId }, 'integration-admin');
    await devices.heartbeat(next.deviceId);
    const latest = await agent.get(`/api/v1/patients/${patientId}/latest`);
    expect(latest.body.data).toBeNull();
    expect(latest.body.meta).toMatchObject({ ageMs: null, stale: true, connectionState: 'connected_without_valid_reading' });
    expect((await agent.get(`/api/v1/patients/${patientId}/measurements`)).body.data[0].deviceId).toBe(deviceId);
    await db.collection('users').doc(uid).update({ enabled: false });
    expect((await agent.get(`/api/v1/patients/${patientId}`)).status).toBe(403);
  }, 30000);
});
